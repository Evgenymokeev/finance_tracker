"""
Базовые интерфейсы и исключения для провайдеров уведомлений.

Провайдер отвечает только за взаимодействие с внешним каналом.
Управление статусами NotificationDelivery, повторными попытками,
lease и сохранением результатов остаётся ответственностью
DeliveryProcessor.
"""

from abc import ABC, abstractmethod


class DeliveryError(Exception):
    """
    Базовая ошибка отправки уведомления.

    Все ошибки провайдеров должны наследоваться от этого класса,
    чтобы DeliveryProcessor мог централизованно классифицировать
    результат попытки отправки.
    """


class TemporaryDeliveryError(DeliveryError):
    """
    Временная ошибка, после которой отправку можно повторить.

    Примеры:
    - временная недоступность SMTP-сервера;
    - сетевой сбой;
    - временный отказ внешнего сервиса;
    - ограничение частоты запросов.
    """


class PermanentDeliveryError(DeliveryError):
    """
    Постоянная ошибка, при которой повторная отправка бессмысленна.

    Примеры:
    - некорректный адрес получателя;
    - адрес отклонён как недействительный;
    - ошибка конфигурации, требующая вмешательства оператора.
    """


class BaseSender(ABC):
    """
    Абстрактный интерфейс провайдера доставки уведомлений.

    Реализации должны отправлять уведомление и возвращать
    результат отправки либо выбрасывать одно из типизированных
    исключений DeliveryError.

    Провайдер не изменяет состояние NotificationDelivery.
    """

    @abstractmethod
    def send(self, delivery):
        """
        Отправляет уведомление через соответствующий канал.

        Аргументы:
            delivery: экземпляр NotificationDelivery.

        Возвращает:
            Результат отправки, определяемый конкретным провайдером.

        Исключения:
            TemporaryDeliveryError: временная ошибка отправки.
            PermanentDeliveryError: постоянная ошибка отправки.
        """
        raise NotImplementedError
